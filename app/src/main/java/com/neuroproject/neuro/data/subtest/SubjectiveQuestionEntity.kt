package com.neuroproject.neuro.data.subtest

import androidx.room.Entity
import androidx.room.PrimaryKey

/**
 * Тип блока вопросов субъективного тестирования
 *
 * Определяет категорию вопросов для оценки различных аспектов состояния пользователя.
 *
 * @property COGNITIVE Когнитивный блок - вопросы о мышлении, концентрации, принятии решений
 * @property EMOTIONAL Эмоциональный блок - вопросы о настроении, эмоциональной стабильности
 * @property PHYSICAL Физический блок - вопросы о физическом состоянии, энергии, усталости
 */
enum class BlockType {
    COGNITIVE,   // Когнитивное состояние
    EMOTIONAL,   // Эмоциональное состояние
    PHYSICAL     // Физическое состояние
}

/**
 * Сущность вопроса субъективного тестирования
 *
 * Содержит текст вопроса и его параметры. Вопросы разделены на три блока:
 * когнитивный, эмоциональный и физический. Каждый вопрос оценивается по шкале от 1 до 10.
 *
 * ## Структура теста:
 * - **Когнитивный блок** (10 вопросов) - оценивает концентрацию, скорость мышления, принятие решений
 * - **Эмоциональный блок** (10 вопросов) - оценивает настроение, стабильность, стресс
 * - **Физический блок** (10 вопросов) - оценивает энергичность, усталость, физическое состояние
 *
 * ## Обработка обратных вопросов:
 * Некоторые вопросы являются обратными ([isReversed] = true):
 * - Прямые вопросы: чем выше балл, тем хуже состояние
 * - Обратные вопросы: чем выше балл, тем лучше состояние
 *
 * При расчете итоговых индексов значения обратных вопросов инвертируются:
 * ```
 * normalizedValue = isReversed ? (maxValue + minValue - value) : value
 * ```
 *
 * @property id Уникальный идентификатор вопроса (1-30)
 * @property text Текст вопроса
 * @property blockType Тип блока (когнитивный/эмоциональный/физический)
 * @property displayOrder Порядок отображения в блоке (1-10)
 * @property isReversed Флаг обратного вопроса (true - положительный вопрос)
 * @property minValue Минимальное значение шкалы (по умолчанию 1)
 * @property maxValue Максимальное значение шкалы (по умолчанию 10)
 *
 * @see BlockType
 */
@Entity(tableName = "subjective_questions")
data class SubjectiveQuestionEntity(
    @PrimaryKey
    val id: Int,                           // ID вопроса (1-30)
    val text: String,                      // Текст вопроса
    val blockType: BlockType,              // Тип блока
    val displayOrder: Int,                 // Порядок отображения
    val isReversed: Boolean,               // Является ли вопрос обратным

    val minValue: Int = 1,                 // Минимальное значение ответа
    val maxValue: Int = 10                 // Максимальное значение ответа
)